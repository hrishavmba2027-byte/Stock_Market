def load_sentiment(client: Any) -> Dict[str, List[Dict[str, Any]]]:
    """Return {ticker: [snapshot per source]} from ``sentiment_latest``."""
    out: Dict[str, List[Dict[str, Any]]] = {}
    for doc in client.collection(SENTIMENT_COLLECTION).stream():
        data = doc.to_dict() or {}
        ticker = data.get("ticker")
        if ticker:
            out.setdefault(ticker, []).append(
                {
                    k: data.get(k)
                    for k in (
                        "source", "as_of_date", "sent_mean_3d", "sent_mean_7d",
                        "sent_pos_share", "sent_neg_share", "n_3d", "n_7d",
                    )
                }
            )
    return out


def sentiment_context_for(ticker: str, sentiment: Dict[str, List[Dict[str, Any]]]) -> Dict[str, Any]:
    """Assemble the sentiment a single stock is allowed to see.

    Returns the company's own sentiment, its sector's sentiment, and the GENERAL
    macro sentiment — and nothing else. Other companies' and other sectors'
    sentiment is deliberately excluded so the LLM only weighs signals relevant
    to this stock.
    """
    sector = sector_for(ticker)
    sector_entity = sector_entity_id(sector) if sector and sector != "Unknown" else None
    return {
        "company": sentiment.get(ticker),
        "sector": {
            "name": sector,
            "sentiment": sentiment.get(sector_entity) if sector_entity else None,
        },
        "general": sentiment.get(GENERAL_ENTITY),
    }


def _has_sentiment(context: Dict[str, Any]) -> bool:
    return bool(
        context.get("company")
        or (context.get("sector") or {}).get("sentiment")
        or context.get("general")
    )


def load_fundamentals(client: Any) -> Dict[str, Dict[str, Any]]:
    """Return {ticker: compact fundamentals summary} from ``fundamentals``.

    Reads the per-ticker fundamentals docs written by
    :mod:`ingestion.fundamentals` (``quarters`` keyed by ``YYYYQn``) and keeps
    only the latest ``FUNDAMENTALS_QUARTERS`` quarters, most-recent first, so
    the LLM sees the current fundamentals plus enough history to judge trend.
    """
    out: Dict[str, Dict[str, Any]] = {}
    for doc in client.collection(FUNDAMENTALS_COLLECTION).stream():
        data = doc.to_dict() or {}
        ticker = data.get("ticker") or doc.id
        quarters = data.get("quarters") or {}
        if not ticker or not isinstance(quarters, dict) or not quarters:
            continue
        # Order quarters newest-first by their period-end date (fall back to the
        # quarter label so ordering is stable even if a date is missing).
        ordered = sorted(
            quarters.items(),
            key=lambda kv: (str((kv[1] or {}).get("quarter_end_date") or ""), kv[0]),
            reverse=True,
        )[:FUNDAMENTALS_QUARTERS]
        recent = {
            q: {
                "quarter_end_date": (payload or {}).get("quarter_end_date"),
                "financials": (payload or {}).get("financials") or {},
            }
            for q, payload in ordered
        }
        out[str(ticker).upper()] = {
            "scrape_date": data.get("scrape_date"),
            "latest_quarter": ordered[0][0] if ordered else None,
            "recent_quarters": recent,
        }
    return out


def load_existing_fingerprints(client: Any) -> Dict[str, str]:
    out: Dict[str, str] = {}
    for doc in client.collection(SUGGESTIONS_COLLECTION).stream():
        data = doc.to_dict() or {}
        if data.get("input_fingerprint"):
            out[doc.id] = data["input_fingerprint"]
    return out


def fingerprint(payload: Dict[str, Any]) -> str:
    return hashlib.sha256(
        json.dumps(payload, sort_keys=True, default=str).encode()
    ).hexdigest()


