def load_forecasts(sheet_id: str, tickers: Optional[List[str]] = None) -> Dict[str, Dict[str, Any]]:
    """Return {ticker: {date, close, recent_closes, forecast: {T+1: px, ...}}}.

    Reads worksheets in batched value ranges to stay inside the Sheets
    read-quota (5 batch calls instead of ~98 per-worksheet reads).
    """
    from utils.google_auth import get_gspread_client

    client = get_gspread_client()
    spreadsheet = client.open_by_key(sheet_id)
    titles = [ws.title for ws in spreadsheet.worksheets()]
    if tickers:
        wanted = {t.strip().upper() for t in tickers}
        titles = [t for t in titles if t.upper() in wanted]

    out: Dict[str, Dict[str, Any]] = {}
    for start in range(0, len(titles), BATCH_GET_CHUNK):
        chunk = titles[start:start + BATCH_GET_CHUNK]
        ranges = [f"'{title}'" for title in chunk]
        response = spreadsheet.values_batch_get(ranges)
        for title, vr in zip(chunk, response.get("valueRanges", [])):
            parsed = _parse_worksheet(vr.get("values", []))
            if parsed is not None:
                out[title] = parsed
            else:
                _log(f"[suggest] {title}: no usable forecast row — skipped")
    return out


def _parse_worksheet(values: List[List[str]]) -> Optional[Dict[str, Any]]:
    if not values or len(values) < 2:
        return None
    header = values[0]
    col = {name: idx for idx, name in enumerate(header)}
    if "Close" not in col or FORECAST_COLS[0] not in col:
        return None

    def cell(row: List[str], name: str) -> Optional[str]:
        idx = col.get(name)
        if idx is None or idx >= len(row):
            return None
        return row[idx] if row[idx] != "" else None

    def as_float(raw: Optional[str]) -> Optional[float]:
        if raw is None:
            return None
        try:
            return float(str(raw).replace(",", ""))
        except ValueError:
            return None

    # Latest row that has both a Close and a T+1 forecast.
    latest = None
    closes: List[float] = []
    for row in values[1:]:
        close = as_float(cell(row, "Close"))
        if close is not None:
            closes.append(close)
            if as_float(cell(row, FORECAST_COLS[0])) is not None:
                latest = row
    if latest is None:
        return None

    forecast = {}
    for name in FORECAST_COLS:
        px = as_float(cell(latest, name))
        if px is not None:
            forecast[name.replace("Forecast_Close_", "")] = px
    if not forecast:
        return None

    return {
        "date": cell(latest, "Date"),
        "close": as_float(cell(latest, "Close")),
        "recent_closes": closes[-RECENT_CLOSES:],
        "forecast": forecast,
    }


