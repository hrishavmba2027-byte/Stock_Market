"""GLM trade-suggestion layer (P3 decision layer).

Turns the latest 15-day forecast path per stock (operational Google Sheet),
the latest FinBERT sentiment snapshot (Firestore ``sentiment_latest``), and
the recent quarterly fundamentals (Firestore ``fundamentals``) into a
BUY / HOLD / AVOID suggestion with sell timing and a stop-loss, generated by
GLM (OpenAI-compatible endpoint, e.g. Ollama Cloud glm-4.7) and stored in
Firestore collection ``trade_suggestions`` (one doc per ticker).

Incremental contract ("contextualize once, then only new data"):
every suggestion doc stores an ``input_fingerprint`` — a sha256 of the
forecast path + sentiment snapshot + fundamentals it was generated from. On
later runs a stock is re-sent to the LLM only when that fingerprint changes
(or --force).

Environment:
    GLM_API_KEY   — API key (required)
    GLM_BASE_URL  — OpenAI-compatible base URL (default https://ollama.com/v1)
    GLM_MODEL     — model id (default glm-4.7)
    SHEET_ID / OPERATIONAL_SHEET_ID — operational Google Sheet
    FIREBASE_CREDENTIALS — Firestore service account (see ingestion/_firestore)

Usage:
    python -m features.trade_suggestions                   # all worksheets
    python -m features.trade_suggestions --tickers RELIANCE,TCS
    python -m features.trade_suggestions --dry-run         # no Firestore write
    python -m features.trade_suggestions --force           # ignore fingerprints
"""
