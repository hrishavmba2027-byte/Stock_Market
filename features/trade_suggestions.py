# Global pacing so concurrent workers don't burst past the API rate limit:
# request starts are spaced at least MIN_REQUEST_INTERVAL seconds apart.
_throttle_lock = threading.Lock()
_next_slot = [0.0]


def _throttle() -> None:
    with _throttle_lock:
        now = time.monotonic()
        wait = max(0.0, _next_slot[0] - now)
        _next_slot[0] = max(now, _next_slot[0]) + MIN_REQUEST_INTERVAL
    if wait:
        time.sleep(wait)

