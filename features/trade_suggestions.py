FUNDAMENTALS_QUARTERS = 5  # latest N quarters handed to the LLM for trend context
                           # (rolling window: oldest drops off as a new quarter arrives)

# Suggestion-doc schema version so downstream readers can detect the payload
# shape. v1 = forecast + sentiment only; v2 = adds fundamentals context and the
# sentiment_used / fundamentals_used provenance flags; v3 = sentiment is now
# split into the company's own + its sector's + GENERAL (other companies'/
# sectors' sentiment is never sent to a given stock).
SUGGESTION_SCHEMA_VERSION = 3

GENERAL_ENTITY = "GENERAL"

FORECAST_COLS = [f"Forecast_Close_T+{h}" for h in range(1, 16)]
RECENT_CLOSES = 5           # trailing closes given to the LLM as context
BATCH_GET_CHUNK = 20        # worksheets per Sheets values_batch_get call
